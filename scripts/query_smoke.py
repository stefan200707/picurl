#!/usr/bin/env python3
"""Прогонщик сложных запросов к picurl через FastAPI TestClient.

Запуск (ИИ-слой в этом окружении недоступен — нет кредов и БД):

    AI_ENRICHMENT_ENABLED=false uv run python scripts/query_smoke.py

Скрипт НЕ поднимает сервер: он использует ``fastapi.testclient.TestClient``,
который прогоняет запросы через ASGI-приложение in-process. Для каждого запроса
печатается: сам текст, полученный URL и распознанные фильтры (``criteria``),
а также предупреждения и флаги ИИ.

Единственный сетевой вызов в рантайме — валидация выдачи через backend pik.ru
(``app.pik.validator.validate``). Он best-effort: при недоступности сети сервис
не падает, а ``result_count`` приходит ``None`` с предупреждением
«выдача не проверена». В офлайн-окружении это ожидаемо и дефектом не считается.
"""

from __future__ import annotations

import json
import os

# ИИ-обогащение в этом окружении недоступно (нет кредов и БД). Выключаем ещё до
# импорта приложения, чтобы get_settings() (кэшируется) прочитал корректно.
os.environ.setdefault("AI_ENRICHMENT_ENABLED", "false")

from fastapi.testclient import TestClient  # noqa: E402

from app.main import app  # noqa: E402

# 30 сложных запросов: комнатность, метро, бюджет, отделка, «рядом с …»,
# отрицания, опечатки, смешанные единицы, сленг, противоречия, «вода».
QUERIES: list[str] = [
    # --- комнатность + бюджет + метро + отделка ---
    "хочу двушку у метро, до 15 млн, с отделкой",
    "трёшка рядом с метро Тульская, бюджет 25 млн, под ключ",
    "однушку до 10 миллионов с чистовой отделкой",
    "студия у метро до 8 млн, без отделки",
    "2-комнатную квартиру от 40 до 70 метров, до 18 млн",
    # --- диапазоны и перечисления комнат ---
    "1-2 комнатные квартиры до 12 млн подешевле",
    "нужна 3+ комнатная, площадь побольше",
    "двух или трёхкомнатную у метро Аэропорт, до 30 млн",
    "четырёхкомнатную квартиру, высокий этаж, с отделкой",
    "студию или однушку, до 9 млн, заселение сразу",
    # --- «рядом с …» POI и ориентиры ---
    "двушка рядом с парком, до 20 млн",
    "квартира рядом со школой и детским садом, трёшка",
    "однушка недалеко от метро, с отделкой, до 11 млн",
    "двушку рядом с МГУ, бюджет 25 млн",
    "квартира поближе к центру, до 40 млн, готовый дом",
    # --- отрицания ---
    "двушку не на первом этаже, до 16 млн",
    "трёшка не последний этаж, с отделкой",
    "только квартиры, без апартаментов, до 20 млн",
    "однушка без отделки, не первый этаж, до 10 млн",
    "двухкомнатную, только свободные, не бронь",
    # --- опечатки и сленг ---
    "хачу двушку у митро, да 15 млн, с атделкой",
    "трешка падешевле, кухня от 12 метров",
    "нужна хата двушка за 15 лямов у метро",
    "аднушка до 8 млн бабки есть, с ремонтом",
    "двушечку рядом с парком, штоб недорого, до 14 млн",
    # --- смешанные единицы и слитные суффиксы ---
    "квартира до 15м, площадь от 55 м2, двушка",
    "трёшка бюджет 800к... нет, 18 миллионов, с отделкой",
    "однушка от 30 до 45 кв.м, до 9500000 рублей",
    "двушка с 5 по 20 этаж, до 20 млн, кухня от 10",
    # --- «вода», противоречия и неподдерживаемое ---
    "хочу вторичку двушку кирпичный дом на южную сторону до 15 млн",
]


def _fmt(value: object) -> str:
    """Компактный JSON-дамп с кириллицей как есть."""
    return json.dumps(value, ensure_ascii=False)


def main() -> None:
    print(f"picurl query smoke — {len(QUERIES)} запросов")
    print(f"AI_ENRICHMENT_ENABLED={os.environ.get('AI_ENRICHMENT_ENABLED')!r}\n")

    # Контекст-менеджер запускает lifespan приложения (создаёт http-клиент).
    with TestClient(app) as client:
        for i, query in enumerate(QUERIES, start=1):
            print("=" * 88)
            print(f"[{i:02d}/{len(QUERIES)}] Запрос: {query}")
            try:
                resp = client.post("/build-url", json={"text": query})
            except Exception as exc:  # pragma: no cover - защита прогонщика
                print(f"  !! исключение запроса: {exc!r}")
                continue

            if resp.status_code != 200:
                print(f"  !! HTTP {resp.status_code}: {resp.text}")
                continue

            data = resp.json()
            print(f"  URL:       {data['url']}")
            print(f"  Фильтры:   {_fmt(data['criteria'])}")
            print(f"  result_count: {data['result_count']}")
            print(f"  warnings:  {_fmt(data['warnings'])}")
            print(
                "  ai: used={ai_used} cache_hit={cache_hit} explanation={expl}".format(
                    ai_used=data["ai_used"],
                    cache_hit=data["ai_cache_hit"],
                    expl=_fmt(data["ai_explanation"]),
                )
            )
    print("=" * 88)
    print("готово")


if __name__ == "__main__":
    main()
