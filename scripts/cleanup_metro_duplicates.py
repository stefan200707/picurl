"""Разовая кураторская чистка ``app/reference/metro.json``.

Контекст: после гео-обогащения станций из OSM (``refresh_metro_geo.py``, 379
записей, 350 получили lat/lon/line) в справочнике осталось 29 записей без
координат — исторический мусор вперемешку с реальными, но пока не
привязанными к OSM станциями. Этот скрипт наводит порядок по итогам ручного
разбора каждой из 29 записей (проверено через Wikipedia; полный разбор — в
отчёте задачи, не хранится в репозитории).

Правила решения (см. также CLAUDE.md, раздел «Справочники»):
    - запись с непустым ``slug``/``id`` никогда не удаляется — максимум
      сливается в основную запись как алиас (имя + все алиасы дубля
      переносятся в aliases основной записи, дубль после этого убирается из
      списка);
    - станции других городов удаляются без переноса алиасов;
    - переименованные/дубли-заглушки сливаются в актуальную запись;
    - реальные, но пока геонепривязанные московские станции остаются как
      есть (это не мусор, а задокументированный пробел OSM);
    - строящиеся станции с датой в названии остаются, дата переносится в
      алиас, имя приводится к чистому виду.

Скрипт идемпотентен: повторный запуск на уже вычищенном файле не меняет его
(дубликаты и так отсутствуют). Формат записи на диск — тот же, что и у
``app/reference/refresh.py`` (тот же ``write_entries``/``load_existing``,
та же сортировка), чтобы следующий прогон ``refresh`` не дал мусорного диффа.

.. important::
    **Инцидент (см. CLAUDE.md, раздел «Справочники»):** первая версия этого
    скрипта слила в ``MERGE_INTO`` семь записей, у которых был непустой
    ``id`` (GUID станции — самый дефицитный ресурс справочника, докуривается
    вручную и не добывается ни OSM, ни refresh-скриптом), — «Крюково»,
    «Кунцевская (БКЛ)», «Кунцевская (Филёвская)», «МЦД-1 Кунцевская»,
    «МЦК Бульвар Рокоссовского», «МЦК Шоссе Энтузиастов», «Очаково I». Их GUID
    физически различают разные значения фильтра ``metroStations`` на pik.ru
    (разные платформы/линии одной физической станции), поэтому слияние в одну
    запись с одним id — не косметика, а порча справочника (выдача сужается
    до одной платформы вместо всех). Восстановлены как самостоятельные записи
    вручную; из ``MERGE_INTO`` эти семь ключей удалены навсегда. Функция
    :func:`cleanup` теперь **запрещает** сливать запись с непустым ``id``/
    ``slug`` — падает с explicit ``ValueError`` вместо тихой потери GUID.
    Это первопричина инцидента, а не только его последствие.

Запуск: ``uv run python scripts/cleanup_metro_duplicates.py``.
"""

from __future__ import annotations

from app.reference.loader import DATA_DIR, RefEntry, normalize
from app.reference.refresh import load_existing, write_entries

METRO_PATH = DATA_DIR / "metro.json"

#: Станции других городов (СПб/Казань/Екатеринбург) — в московском справочнике
#: pik.ru им не место. Алиасы никуда не переносятся (не относятся к Москве).
DELETE_OTHER_CITY: set[str] = {
    "Ботаническая",  # Екатеринбургский метрополитен / планируемая станция СПб
    "Девяткино",  # Петербургский метрополитен
    "Ладожская",  # Петербургский метрополитен
    "Обводный канал",  # Петербургский метрополитен
    "Приморская",  # Петербургский метрополитен
    "Проспект Ветеранов",  # Петербургский метрополитен
    "Суконная слобода",  # Казанский метрополитен
}

#: Точные дубли-заглушки без собственной ценности (нет slug/id, содержимое уже
#: полностью покрыто существующей полноценной записью буква в букву/по сути).
DELETE_REDUNDANT_STUB: set[str] = {
    "Бутырская ",  # с хвостовым пробелом; дубль "Бутырская" (id+lat/lon)
    "Красный строитель",  # регистро-дубль "Красный Строитель" (id+lat/lon+alias)
    "Новомосковская (Коммунарка)",  # обе станции уже есть отдельно с координатами
}

#: Слияния: имя дубля -> имя основной записи, в которую переносятся имя дубля
#: и все его алиасы (см. докстринг модуля). Дубль удаляется из списка.
#: ВАЖНО: сюда нельзя класть запись с непустым id/slug (см. ``.. important::``
#: в докстринге модуля) — :func:`cleanup` теперь явно запрещает такое слияние.
MERGE_INTO: dict[str, str] = {
    "Библиотека им.Ленина": "Библиотека имени Ленина",
    "Деловой центр (Выставочная)": "Деловой центр",
    "Матвеевское": "Матвеевская",
    "Покровское-Стрешнево": "Стрешнево",
    "Тестовская": "Москва-Сити",
}

#: Дополнительный алиас, добавляемый в основную запись при слиянии (сверх
#: имени дубля и его собственных алиасов) — там, где полезное для матчинга
#: имя отличается от буквального имени дубля-заглушки.
EXTRA_MERGE_ALIASES: dict[str, str] = {
    "Деловой центр (Выставочная)": "Выставочная",
}

#: Строящиеся станции с датой в названии: остаются (реальные строящиеся
#: станции БКЛ, подтверждено), дата уходит в алиас, имя приводится к чистому
#: виду.
RENAME_STRIP_DATE: dict[str, str] = {
    "Липовая Роща 2027 год": "Липовая Роща",
    "Новорижская 2027 год": "Новорижская",
}


def _add_aliases(entry: RefEntry, *new_aliases: str) -> RefEntry:
    """Добавить алиасы к записи, не потеряв и не задублировав существующие."""
    seen = {normalize(entry.name)} | {normalize(a) for a in entry.aliases}
    result = list(entry.aliases)
    for alias in new_aliases:
        key = normalize(alias)
        if key and key not in seen:
            seen.add(key)
            result.append(alias)
    return entry.model_copy(update={"aliases": tuple(result)})


def cleanup(entries: list[RefEntry]) -> list[RefEntry]:
    """Применить все решения к списку записей метро (чистая функция)."""
    by_name = {entry.name: entry for entry in entries}

    unknown = (
        set(DELETE_OTHER_CITY)
        | set(DELETE_REDUNDANT_STUB)
        | set(MERGE_INTO)
        | set(RENAME_STRIP_DATE)
    ) - by_name.keys()
    if unknown:
        raise ValueError(f"Записи не найдены в metro.json (уже применено?): {sorted(unknown)}")

    # Слияния: перенести имя дубля + его алиасы (+ доп. алиас) в основную запись.
    for dup_name, target_name in MERGE_INTO.items():
        dup = by_name[dup_name]
        if dup.id or dup.slug:
            # Первопричина инцидента с потерей 7 GUID (см. ``.. important::``
            # в докстринге модуля): слияние ЗАПИСИ-НОСИТЕЛЯ GUID/slug в другую
            # запись безвозвратно теряет её id/slug (в результирующей записи
            # остаётся только id/slug основной записи). GUID станции — самый
            # дефицитный ресурс справочника (докуривается вручную, ни OSM, ни
            # refresh его не восстановят), поэтому такое слияние запрещено
            # безусловно: явная ошибка вместо тихой потери данных.
            raise ValueError(
                f"Слияние запрещено: {dup_name!r} имеет непустой id/slug "
                f"(id={dup.id!r}, slug={dup.slug!r}) — слияние в {target_name!r} "
                "безвозвратно потеряло бы GUID/slug. Если записи физически "
                "разные значения фильтра pik.ru (частый случай для станций с "
                "несколькими платформами/линиями) — оставь их отдельными "
                "записями, а не сливай."
            )
        target = by_name[target_name]
        extra = EXTRA_MERGE_ALIASES.get(dup_name)
        new_aliases = (dup_name, *dup.aliases, *((extra,) if extra else ()))
        by_name[target_name] = _add_aliases(target, *new_aliases)

    # Переименования строящихся станций: чистое имя + старое имя в алиас.
    for old_name, clean_name in RENAME_STRIP_DATE.items():
        entry = by_name[old_name]
        by_name[clean_name] = _add_aliases(entry, old_name).model_copy(update={"name": clean_name})

    to_drop = set(DELETE_OTHER_CITY) | set(DELETE_REDUNDANT_STUB) | set(MERGE_INTO)
    to_drop |= set(RENAME_STRIP_DATE) - set(RENAME_STRIP_DATE.values())

    result = [entry for name, entry in by_name.items() if name not in to_drop]
    return sorted(result, key=lambda entry: (normalize(entry.name), entry.slug or ""))


def main() -> int:
    entries = load_existing(METRO_PATH)
    before = len(entries)
    cleaned = cleanup(entries)
    write_entries(METRO_PATH, cleaned)
    with_coords = sum(1 for e in cleaned if e.lat is not None and e.lon is not None)
    print(f"metro.json: {before} -> {len(cleaned)} записей ({with_coords} с координатами)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
