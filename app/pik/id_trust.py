"""Реестр недостоверных id станций метро (аудит validate(), 2026-07-23).

Живые замеры curl против ``api.pik.ru/v2/filter`` и ручной разбор
``RefEntry.id`` в ``metro.json`` нашли два разных класса проблемы:

1. **Доказанно синтетические id** — hex-«лесенка» одной серии («Коммунарка»
   ``c1d2e3f4-a5b6-7c8d-9e0f-1a2b3c4d5e6f``, «Одинцово»
   ``a1b2c3d4-e5f6-7a8b-9c0d-1e2f3a4b5c6d``, «Баковка»
   ``b1c2d3e4-f5a6-7b8c-9d0e-1f2a3b4c5d6e`` — с виду один шаблон, у которого
   меняли цифры руками) и текстовые guid-заглушки («Варшавская»
   ``guid-varshavskaya``, «Сокол» ``guid-sokol`` — вообще не в формате GUID, а
   строка-напоминалка «сюда потом вписать GUID»). Их id **физически вычищен**
   из ``app/reference/metro.json`` (сами записи — имя/алиасы/координаты —
   сохранены, они по-прежнему нужны гео-механике). ``REMOVED_SYNTHETIC_
   METRO_IDS`` хранит эти значения только для истории/регрессионных тестов —
   в рантайме они больше нигде не встретятся, т.к. поле ``id`` у этих записей
   теперь ``None``.

2. **Структурно подозрительные, но НЕ доказанные id** — «Митино»
   (``23bd023f-e8b3-469b-98f2-d9633e6fa16b``) и «Мякинино»
   (``23bd023f-e8b3-469b-98f2-d9633e6fa16c``): оба в формате честного
   UUIDv4, тогда как все остальные 61 подтверждённых по формату GUID
   справочника — единый паттерн time-ordered UUIDv6 (``1ee7…``/``1eed…``/
   ``1eeb…``/``1ef0…``/``1ef7…``); и различаются друг от друга только
   последним символом. Этого достаточно, чтобы не доверять id слепо, но
   недостаточно, чтобы объявить его фейком без независимой проверки —
   front-API, который мог бы её дать, закрыт бот-защитой Qrator. Пока разбор
   не сделан вручную, id **остаётся** в JSON (мы не утверждаем, что он
   неверен), но код не подставляет его в URL как штатный ``metroStations``
   (см. :func:`is_verified_metro_id` и geo-фолбэк в
   ``app/pik/location_fallback.py``).

Мотивация всего модуля — задача «Б» аудита: недостоверный id не должен
молча попадать в ссылку под видом настоящего, а запись без достоверного id
обязана участвовать в честном geo-фолбэке (задача «В»), а не тихо выпадать.
"""

from __future__ import annotations

#: Id, которые физически вычищены из ``metro.json`` как доказанно
#: синтетические (см. докстринг модуля, п.1). Хранится для регрессионных
#: тестов («не появились снова») — в рантайме уже не встречается.
REMOVED_SYNTHETIC_METRO_IDS: frozenset[str] = frozenset(
    {
        "c1d2e3f4-a5b6-7c8d-9e0f-1a2b3c4d5e6f",  # Коммунарка
        "a1b2c3d4-e5f6-7a8b-9c0d-1e2f3a4b5c6d",  # Одинцово
        "b1c2d3e4-f5a6-7b8c-9d0e-1f2a3b4c5d6e",  # Баковка
        "guid-varshavskaya",  # Варшавская
        "guid-sokol",  # Сокол
    }
)

#: Id, оставленные в ``metro.json`` (не доказаны фейком), но структурно
#: подозрительные — до ручной докурировки формально считаем недостоверными
#: (см. докстринг модуля, п.2).
SUSPICIOUS_METRO_IDS: frozenset[str] = frozenset(
    {
        "23bd023f-e8b3-469b-98f2-d9633e6fa16b",  # Митино
        "23bd023f-e8b3-469b-98f2-d9633e6fa16c",  # Мякинино
    }
)

#: Полный реестр id, недопустимых как значение штатного query-параметра
#: ``metroStations`` — ни доказанно фейковые (для истории — их уже физически
#: нет в ``metro.json``), ни пока не подтверждённые подозрительные.
UNVERIFIED_METRO_IDS: frozenset[str] = REMOVED_SYNTHETIC_METRO_IDS | SUSPICIOUS_METRO_IDS


def is_verified_metro_id(entity_id: str | None) -> bool:
    """id считается достоверным, если он задан и не входит в реестр недостоверных."""
    return bool(entity_id) and entity_id not in UNVERIFIED_METRO_IDS
