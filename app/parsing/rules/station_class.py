def _official_line_stem_map() -> tuple[tuple[str, str], ...]:
    """Стемы ОФИЦИАЛЬНЫХ имён линий из ``metro.json`` → каноническое имя.

    Milestone AI-21, живой баг: «в районе Троицкой ветки» — AI-17 покрывал
    цвета/номера/прозвища, но не прямые имена линий («Троицкой»,
    «Сокольнической»). Имена берутся из данных (``RefEntry.line``,
    см. ``app.reference.refresh_metro_geo``), а не дублируются строками в
    коде — появится новая линия в справочнике, стем появится сам.

    Стем: у каждого слова нормализованного имени отрезается окончание «ая»
    («троицкая» → «троицк», «арбатско-покровская» → «арбатско-покровск») —
    ``_carrier_pattern`` добавит ``\\w*``, покрывая все склонения («Троицкой»,
    «Сокольнической»). Имена, не оканчивающиеся на «ая» (не прилагательные),
    пропускаются — для них стем-подход дал бы ложные срабатывания. Слово-
    носитель «ветка»/«линия» обязателен (тот же принцип, что у цветов):
    «в районе Троицка» (город) без носителя не матчится.

    Собственного ``@cache`` у функции НЕТ намеренно: кэшем владеет
    ``load_metro()`` (его сбрасывает ``loader.clear_cache()`` — фикстуры
    тестов подменяют справочник, и застывшая здесь копия пережила бы подмену);
    компиляция regex кэшируется отдельно, по содержимому карты
    (:func:`_line_patterns_for`).
    """
    from app.reference.loader import load_metro, normalize

    lines: set[str] = set()
    for entry in load_metro():
        if entry.line:
            lines.update(part.strip() for part in entry.line.split(" / "))

    result: list[tuple[str, str]] = []
    for line in sorted(lines):
        norm_line = normalize(line)
        if norm_line in _LINE_NAME_EXCLUDED or norm_line.startswith("мцд"):
            continue
        words = norm_line.split()
        if not all(w.endswith("ая") for w in words):
            continue
        stem = r"[-\s]+".join(re.escape(w[:-2]) for w in words)
        result.append((stem, line))
    return tuple(result)


@cache
def _line_patterns_for(
    stem_map: tuple[tuple[str, str], ...],
) -> tuple[tuple[re.Pattern[str], str], ...]:
    """Скомпилированные паттерны для карты стемов (кэш по её содержимому).

    Ключ кэша — сама карта: подменили справочник в тестах → карта другая →
    новый набор паттернов, а не застывшая копия старого.
    """
    return tuple((_carrier_pattern(stem), line) for stem, line in stem_map)


#: Прозвища с общей подстрокой «кольцо»/«кольцевая» — проверяются в порядке от
#: более конкретных к общему («большая кольцевая»/«БКЛ»/«центральное кольцо»
#: раньше голого «кольцо»/«кольцевая»), иначе общий паттерн ниже откусил бы
#: «кольцевая» изнутри «большая кольцевая» и дал неверную линию.
#: Общий хвост-исключение «(авто)дорога» после «кольцо/кольцевая» — защита от
#: МКАД/ЦКАД («большая кольцевая автодорога», «центральная кольцевая дорога»)
#: применена единообразно и к специфичным прозвищам, и к общему паттерну ниже.
_NOT_ROAD_TAIL = r"(?!\s*(?:авто)?дорог\w*)"

_SPECIFIC_NICKNAME_PATTERNS: list[tuple[re.Pattern[str], list[str]]] = [
    (re.compile(r"\bбкл\b" + _DISTANCE_AFTER), ["Большая кольцевая"]),
    (
        re.compile(r"\bбольш\w*\s+кольц\w+\b" + _NOT_ROAD_TAIL + _DISTANCE_AFTER),
        ["Большая кольцевая"],
    ),
    (
        re.compile(r"\bцентральн\w*\s+кольц\w+\b" + _NOT_ROAD_TAIL + _DISTANCE_AFTER),
        ["МЦК"],
    ),
    (re.compile(r"\bдиаметр\w*\b" + _DISTANCE_AFTER), ["МЦД"]),
]

#: Общее «кольцо»/«кольцевая» в любой словоформе → Кольцевая линия. Исключение
#: «не считать перед (авто)дорогой» защищает от МКАД («кольцевая дорога») —
#: см. докстринг модуля про остаточный риск.
_GENERIC_RING_PATTERN = re.compile(r"\bкольц\w+\b" + _NOT_ROAD_TAIL + _DISTANCE_AFTER)


def _canonical_line(token: str) -> str:
    """Каноническая форма распознанного класса линии («мцд-2» -> «МЦД-2»)."""
    prefix, sep, suffix = token.partition("-")
    canonical = {"мцд": "МЦД", "мцк": "МЦК"}[prefix]
    return f"{canonical}{sep}{suffix}" if suffix else canonical


def _extract_distance(match: re.Match[str]) -> int | None:
    """Прочитать дистанцию (группы ``dist``/``dist_unit``) из матча, если есть.

    ``match.groupdict()`` возвращает только именованные группы — безопасно
    вызывать и для паттернов без ``_DISTANCE_AFTER``/``dist`` вовсе (вернёт
    пустой словарь).
    """
    groups = match.groupdict()
    dist_raw = groups.get("dist")
    if dist_raw is None:
        return None
    return _parse_distance_meters(dist_raw, groups["dist_unit"])


def _add_matches(
    norm: str,
    text: str,
    pattern: re.Pattern[str],
    lines: list[str],
    reqs: list[StationClassRequirement],
    spans: list[Span],
) -> None:
    """Добавить требования для всех непересекающихся совпадений ``pattern``.

    Один найденный фрагмент → по одному ``StationClassRequirement`` на каждую
    линию из ``lines`` (см. докстринг модуля про «жёлтую»/«восьмую»), но один
    ``Span`` — фрагмент засчитывается «понятым» один раз. Дистанция (если
    паттерн её захватывает — см. ``_DISTANCE_AFTER``) одна на весь фрагмент,
    поэтому применяется к каждому из добавленных требований одинаково.
    """
    for match in pattern.finditer(norm):
        span = match.span()
        if _overlaps(span, spans):
            continue
        raw = text[span[0] : span[1]]
        max_distance_m = _extract_distance(match)
        for line in lines:
            reqs.append(
                StationClassRequirement(line_prefix=line, raw=raw, max_distance_m=max_distance_m)
            )
        spans.append(span)


def extract_station_class_requirements(
    text: str,
) -> tuple[list[StationClassRequirement], list[Span]]:
    """Извлечь требования «рядом с любой станцией класса» из свободного текста.

    Возвращает пару ``(requirements, consumed_spans)`` — по аналогии с
    :func:`app.parsing.rules.landmark.extract_landmark_requirements`.
    """
    norm = _normalize(text)
    reqs: list[StationClassRequirement] = []
    spans: list[Span] = []

    # Дистанция ДО линии («в пределах 700 метров от МЦД-3») — проверяем первой:
    # структурно она перекрывает и саму линию, и предшествующую дистанцию, так
    # что _EXPLICIT_LINE_PATTERN ниже (которому нужен маркер близости «у»/
    # «рядом с», отсутствующий у предлога «от») её просто не тронет — overlap-
    # проверка здесь для единообразия с остальным кодом функции, а не по
    # необходимости.
    for match in _DISTANCE_BEFORE_EXPLICIT_LINE_PATTERN.finditer(norm):
        span = match.span()
        if _overlaps(span, spans):
            continue
        reqs.append(
            StationClassRequirement(
                line_prefix=_canonical_line(match.group("line")),
                raw=text[span[0] : span[1]],
                max_distance_m=_extract_distance(match),
            )
        )
        spans.append(span)

    for match in _EXPLICIT_LINE_PATTERN.finditer(norm):
        span = match.span()
        if _overlaps(span, spans):
            continue
        reqs.append(
            StationClassRequirement(
                line_prefix=_canonical_line(match.group("line")),
                raw=text[span[0] : span[1]],
                max_distance_m=_extract_distance(match),
            )
        )
        spans.append(span)

    for pattern in (_ANY_BEFORE_PATTERN, _ANY_AFTER_PATTERN):
        for match in pattern.finditer(norm):
            span = match.span()
            if _overlaps(span, spans):
                continue
            reqs.append(
                StationClassRequirement(
                    line_prefix="метро",
                    raw=text[span[0] : span[1]],
                    max_distance_m=_extract_distance(match),
                )
            )
            spans.append(span)

    # Разговорные названия (Milestone AI-17). Порядок важен: составные цвета
    # и специфичные прозвища «кольца» проверяются раньше общих паттернов,
    # которые их подстрокой перекрывают (см. докстринг модуля).
    for compound_stem, lines in _COMPOUND_COLOR_LINE_MAP.items():
        _add_matches(norm, text, _carrier_pattern(compound_stem), lines, reqs, spans)

    # Официальные имена линий из metro.json (Milestone AI-21): «Троицкой
    # ветки», «Сокольнической линии». До простых цветов — приоритет у точного
    # имени; пересечений со стемами цветов нет, порядок здесь — на будущее.
    for pattern, line in _line_patterns_for(_official_line_stem_map()):
        _add_matches(norm, text, pattern, [line], reqs, spans)

    for stem, lines in _COLOR_LINE_MAP.items():
        _add_matches(norm, text, _carrier_pattern(stem), lines, reqs, spans)

    for stem, lines in _ORDINAL_LINE_MAP.items():
        _add_matches(norm, text, _carrier_pattern(stem), lines, reqs, spans)

    for pattern, lines in _SPECIFIC_NICKNAME_PATTERNS:
        _add_matches(norm, text, pattern, lines, reqs, spans)

    _add_matches(norm, text, _GENERIC_RING_PATTERN, ["Кольцевая"], reqs, spans)

    return reqs, spans
