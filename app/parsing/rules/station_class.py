#: Слово-носитель («ветка»/«линия», любая словоформа) — единственная защита
#: от ложных срабатываний цвета/номера без явного маркера близости (см.
#: докстринг модуля). Порядок «прилагательное носитель» и «носитель
#: прилагательное» поддержаны оба (по аналогии с обратным порядком слов у
#: area/floor, см. CLAUDE.md, раздел про стресс-тест парсера).
_CARRIER = r"(?:ветк|лини)\w*"


def _carrier_pattern(stem: str) -> re.Pattern[str]:
    """Скомпилировать паттерн «<стем><окончание> + носитель» (оба порядка).

    ``_DISTANCE_AFTER`` приклеен ВНЕ альтернации веток порядка слов (одной
    группой на весь паттерн) — иначе именованные группы ``dist``/``dist_unit``
    задвоились бы внутри одного regex, что Python re запрещает.
    """
    return re.compile(
        rf"(?:\b{stem}\w*\s+{_CARRIER}\b|\b{_CARRIER}\s+{stem}\w*\b){_DISTANCE_AFTER}"
    )


