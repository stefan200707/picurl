#
# - «после»: маркер + линия + дистанция («у МЦД в 500 метрах», «рядом с МЦД не
#   дальше 800 м», «у коричневой ветки в 1 км») — общий суффикс
#   ``_DISTANCE_AFTER``, приклеенный к каждому уже существующему паттерну линии
#   (явная линия, «любая станция», цвета/номера/прозвища) РОВНО один раз (вне
#   альтернации внутри самого паттерна — иначе именованные группы
#   ``dist``/``dist_unit`` задвоились бы в одном regex, что Python re не
#   допускает);
# - «до»: дистанция + предлог «от» + линия («в пределах 700 метров от МЦД-3») —
#   отдельный паттерн ``_DISTANCE_BEFORE_EXPLICIT_LINE_PATTERN``: структура
#   принципиально другая (нет маркера близости ``_MARKER`` перед числом,
#   объект вводится предлогом «от», а не «у»/«рядом с»).
#
# «В пешей доступности» (без числа) сознательно НЕ превращается в
# ``max_distance_m`` константой — это МЯГКОЕ пожелание, а не жёсткая
# пользовательская отсечка, и уже покрывается дефолтным поведением
# (``STATION_CLASS_DEFAULT_RADIUS_M`` в ``app/geo/candidates.py`` — тот же
# порядок величины, «пешая доступность до станции», см. CLAUDE.md). Если бы
# фраза заполняла ``max_distance_m``, это сломало бы фолбэк на ближайшие ЖК
# (Milestone AI-18): фолбэк специально отключается только при явной
# пользовательской отсечке дистанции, а «в пешей доступности» — это как раз
# «примерно рядом», для которого фолбэк и был придуман. Поэтому хвост только
# консьюмится (не остаётся в warnings), значение не заводится.
_WALK_TAIL = r"в\s+пешей\s+доступности"

#: Дистанция ПОСЛЕ линии/класса — оба варианта (числовая дистанция ИЛИ мягкий
#: хвост «в пешей доступности») в одной альтернации, целиком опциональной.
_DISTANCE_AFTER = (
    rf"(?:\s+(?:{_DIST_MARKER}\s*)?(?P<dist>{_DIST_NUM})\s*(?P<dist_unit>{_DIST_UNIT})"
    rf"|\s+{_WALK_TAIL})?"
)

_EXPLICIT_LINE_PATTERN = re.compile(
    _MARKER
    + r"(?:станци\w*\s+|линии\s+)?(?P<line>"
    + _LINE_TOKEN
    + r")"
    + _QUALIFIER_TAIL
    + _DISTANCE_AFTER
)

#: Дистанция ДО линии/класса, связанная предлогом «от» («в пределах 700
#: метров от МЦД-3»): маркер расстояния здесь необязателен, а вот сама
#: дистанция и предлог «от» — обязательная часть паттерна (иначе это была бы
#: не дистанция, а что-то другое; ложных срабатываний на голое «от МЦД-3» без
#: числа перед ним это не даёт, только на числовую дистанцию + «от»).
_DISTANCE_BEFORE_EXPLICIT_LINE_PATTERN = re.compile(
    rf"(?:{_DIST_MARKER}\s*)?(?P<dist>{_DIST_NUM})\s*(?P<dist_unit>{_DIST_UNIT})\s+от\s+"
    r"(?:станци\w*\s+|линии\s+)?(?P<line>" + _LINE_TOKEN + r")" + _QUALIFIER_TAIL
)

#: «Любая станция» без указания конкретной линии, уточнение ДО слова «метро»
#: («у любого метро», «недалеко от любой станции метро»).
_ANY_BEFORE_PATTERN = re.compile(_MARKER + r"люб\w+\s+(?:станци\w*\s+)?метро\b" + _DISTANCE_AFTER)

#: Тот же случай, но уточнение ПОСЛЕ слова «метро» («рядом с метро не важно
#: каким», «рядом с метро не важно какой станции»). Без явного уточнения «у
#: метро» не матчим вообще — это обычная связка перед именем конкретной
#: станции («у метро Аэропорт»), её распознаёт app.parsing.entity_match.
_ANY_AFTER_PATTERN = re.compile(
    _MARKER + r"(?:станци\w*\s+)?метро(?:\s+не\s+важно\s+как\w*(?:\s+станци\w*)?)" + _DISTANCE_AFTER
)

