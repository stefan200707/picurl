"""Regex-правила извлечения структурных фактов из свободного текста (промпт 04).

Каждая функция чистая (без сети и глобального состояния), принимает исходный
текст и возвращает пару ``(значение, consumed_spans)``, где ``consumed_spans`` —
список полуинтервалов ``(start, end)`` индексов **исходного** текста, которые
правило «поняло». Диапазоны нужны фасаду ``parse`` (промпт 06), чтобы вычислить
нераспознанные куски и отправить их в warnings.

Матчинг ведётся по нормализованной копии текста (lowercase + ё→е); нормализация
посимвольная и сохраняет длину строки, поэтому индексы совпадают с исходным
текстом. Все regex компилируются один раз на уровне модуля.

Поддерживаемые факты:

- **комнатность** — «студия», «однушка», «двушка», «трёшка», «2к»,
  «2-комнатную», перечисления («1-2 комнатные»), чип «3+» (и «2+» →
  ``[two, three_plus]``);
- **цена в рублях** — «до 15 млн», «от 10 до 15 млн», «за 15 миллионов»,
  «бюджет 15м», «800 тыс», «до 15 000 000 руб», голые большие числа
  (≥ 100 000 → рубли);
- **площадь** — общая («от 70 м²», «70-100 метров», «площадь от 40») и кухня
  («кухня от 8», «с кухней от 10 метров»); различаются по ключевым словам;
- **этаж** — «с 5 по 20 этаж» → ``floor_min/max``; «не первый», «высокий этаж»
  → ``not_first_floor``; «последний» → ``last_floor`` (с защитой от «не
  последний»);
- **отделка** — «с отделкой»/«чистовая» → ``finish=True``; «без
  отделки»/«черновая» → ``finish=False``;
- **заселение** — «заселение сразу», «готовый дом», «сдан» → ``ready=True``;
- **сортировка** — «подешевле»/«сначала дешевле» → ``price_asc``, «подороже» →
  ``price_desc``, «площадь побольше» → ``area_desc``, «площадь поменьше» →
  ``area_asc``;
- **прочее** — «только квартиры»/«без апартаментов» →
  ``housing_type=flats_only``; «не бронь»/«доступные» → ``only_available``;
- **неподдерживаемое** — каталог заведомо неподдерживаемых pik.ru фильтров
  («вторичка», «сторона света», «раздельный санузел», «материал дома»):
  фильтров нет в схеме сайта, критерии не трогаются, фрагмент возвращается как
  маркер для warning со своим объяснением «не поддерживается pik.ru».

Агрегат :func:`apply_rules` прогоняет все правила и собирает готовый
:class:`~app.parsing.schema.Criteria` + объединённые диапазоны + маркеры.
"""

import re
from collections.abc import Iterable, Iterator

from app.reference.loader import LATIN_TO_CYRILLIC_CONFUSABLES

#: Полуинтервал [start, end) индексов исходного текста, «съеденный» правилом.
Span = tuple[int, int]

# ---------------------------------------------------------------------------
# Нормализация и общие помощники
# ---------------------------------------------------------------------------


def _normalize(text: str) -> str:
    """Нормализовать текст для матчинга, сохранив длину (индексы не съезжают).

    Посимвольно: lowercase (если однобуквенный результат) + ё→е + латинские
    гомоглифы → кириллица (:data:`app.reference.loader.LATIN_TO_CYRILLIC_CONFUSABLES`,
    Milestone AI-20 — «двушкa»/«мeтро» с одной подменённой латинской буквой
    раньше не распознавались вовсе). Гомоглифы заменяются 1:1, инвариант
    «длина строки не меняется» сохраняется. Пробелы не схлопываются —
    regex-паттерны сами используют ``\\s+``.
    """
    out: list[str] = []
    for char in text:
        low = char.lower()
        if len(low) != 1:  # экзотика вроде İ → i̇ ломает индексы; не трогаем
            low = char
        if low == "ё":
            low = "е"
        low = LATIN_TO_CYRILLIC_CONFUSABLES.get(low, low)
        out.append(low)
    return "".join(out)


def _overlaps(span: Span, spans: Iterable[Span]) -> bool:
    """Пересекается ли ``span`` хотя бы с одним из ``spans``."""
    start, end = span
    return any(start < other_end and other_start < end for other_start, other_end in spans)


def _iter_free(
    pattern: re.Pattern[str], text: str, consumed: Iterable[Span]
) -> Iterator[re.Match[str]]:
    """Матчи ``pattern``, не пересекающиеся с уже «съеденными» диапазонами."""
    taken = list(consumed)
    for match in pattern.finditer(text):
        if not _overlaps(match.span(), taken):
            yield match


#: Число: «15», «15,5», «9.5», «15 000 000» (пробел/неразрывный/узкий).
_NUM = r"\d{1,3}(?:[   ]\d{3})+|\d+(?:[.,]\d+)?"

#: Защита от токена «<буквы>-<цифра>» (МЦД-3, МЦК-2, Д-5 и т.п. — номер линии
#: транспорта/класса станции, см. ``app.parsing.rules.station_class``). Общее
#: правило БЕЗ хардкода конкретных линий: если непосредственно перед числом
#: стоит «буква + дефис» без пробела, это число не является границей диапазона
#: (цены/площади) или количеством комнат — оно часть соседнего токена. Не
#: встроено прямо в ``_NUM`` (это расширило бы защиту на все вхождения числа
#: сразу, включая теоретически безопасные вроде «бюджет-15 млн»), а
#: применяется точечно в паттернах ДИАПАЗОНА, где и был обнаружен баг
#: (Milestone AI-16): ``price.py._PRICE_RANGE``, ``area.py._AREA_RANGE``,
#: ``rooms.py._ROOMS_NUM``/``_ROOMS_PLUS``.
_NOT_LINE_NUMBER = r"(?<![^\W\d_]-)"


def _to_number(raw: str) -> float:
    """Разобрать число из текста: разделители тысяч, запятая как точка."""
    cleaned = re.sub(r"[\s\xa0\u202f]", "", raw).replace(",", ".")
    return float(cleaned)


# ---------------------------------------------------------------------------
# Дистанция до объекта: общий фрагмент для POI и класса станций (AI-19)
# ---------------------------------------------------------------------------
#
# И ``rules/poi.py`` («школа в 300 метрах»), и ``rules/station_class.py``
# («у МЦД в 500 метрах») решают одну и ту же задачу — «дистанция до объекта в
# метрах/километрах», различается только текст-носитель вокруг (POI-категория
# vs линия/класс станций). Чтобы не заводить два диалекта одного и того же
# regex, числовая часть + единица измерения и перевод в метры вынесены сюда;
# маркер близости («в»/«не дальше»/«в пределах»/…) и его позиция относительно
# носителя (до/после) — забота вызывающего модуля, там разный контекст.

#: Необязательный маркер перед числом дистанции. Порядок альтернатив — от более
#: длинных фраз к более коротким («в пределах» раньше голого «в»); корректность
#: не зависит от порядка (бэктрекинг regex-движка перепробует все варианты),
#: порядок важен только для читаемости/производительности.
_DIST_MARKER = r"(?:не\s+дальше|не\s+более|не\s+далее|в\s+пределах|максимум|до|в)"

#: Единица дистанции — метры, километры или МИНУТЫ пешей доступности («школа в
#: 15 минутах»). Минуты переводятся в метры в :func:`_parse_distance_meters`
#: через ``WALK_METERS_PER_MINUTE`` (эвристика пешей скорости). Общая единица —
#: выгода сразу для poi/landmark/station-class (единый фрагмент дистанции).
_DIST_UNIT = r"(?:км\b|километр\w*|минут\w*|м\b|метр\w*)"

#: Пешая скорость для перевода «N минут» → метры (калибруемая эвристика:
#: ~80 м/мин ≈ 4.8 км/ч, «пешая доступность»). Только для POI/landmark/
#: station-class гео-сужения — время до метро (URL-фильтр timeOnFoot) считает
#: отдельное правило rules/time.py и в дистанцию не превращается.
WALK_METERS_PER_MINUTE = 80

#: Числовое значение дистанции. Километры часто дробные («1.5 км», «1,5 км» —
#: запятая как разделитель, как и у ``_NUM``), метры почти всегда целые — единый
#: паттерн безопасен для обоих случаев; единицу и перевод в метры разбирает
#: :func:`_parse_distance_meters`.
_DIST_NUM = r"\d+(?:[.,]\d+)?"


def _parse_distance_meters(raw_value: str, unit: str) -> int:
    """Перевести дистанцию (число + единица) в метры.

    Километры (``км``/``километр...``) переводятся умножением на 1000
    (с округлением); метры — как есть, тоже округлённые до целого.
    """
    value = _to_number(raw_value)
    if unit.startswith(("км", "километр")):
        return round(value * 1000)
    if unit.startswith("минут"):
        return round(value * WALK_METERS_PER_MINUTE)
    return round(value)


# ---------------------------------------------------------------------------
# Маркер пространственной близости: общий источник (Milestone AI-20)
# ---------------------------------------------------------------------------
#
# Раньше семантически ОДИН И ТОТ ЖЕ список форм («рядом с», «у», «около»,
# «недалеко от», «вблизи», ...) был продублирован и независимо неполон в ТРЁХ
# местах: TRIGGERS в ``app.parsing.entity_match`` (не было «недалеко от»/
# «около»/«возле»/«неподалёку от»/«вблизи» перед «метро»), ``_MARKER`` в
# ``rules/landmark.py`` (был полным) и ``SUFFIX`` в ``rules/poi.py`` (не было
# «недалеко»). Единый источник закрывает класс дефекта целиком, а не
# конкретные упомянутые в баге фразы.
#
# Управляющий предлог (с/со/к/ко/от) сделан НЕОБЯЗАТЕЛЬНЫМ внутри каждой
# формы — это позволяет использовать один и тот же список ДВУМЯ способами без
# дублирования литералов:
#   - «маркер + объект» (``rules/landmark.py``, ``rules/station_class.py``,
#     ``entity_match``: TRIGGERS и поглощение маркера в consumed span) —
#     вызывающий код сам добавляет обязательный ``\s+`` и паттерн объекта
#     следом («рядом Кремля» без «с» тоже технически совпадёт с маркером, но
#     это не даёт новых ложных срабатываний — объект всё равно должен
#     самостоятельно пройти нечёткое сопоставление со справочником);
#   - «маркер сам по себе, без объекта» (``rules/poi.py``: SUFFIX — «школа
#     недалеко», «садик поблизости») — предлог тут и не должен присутствовать,
#     а раньше «недалеко» без «от» не матчилось вовсе.
_PROXIMITY_MARKER = (
    r"(?:"
    r"рядом(?:\s+с|\s+со)?|"
    r"поближе(?:\s+к|\s+ко)?|ближе(?:\s+к|\s+ко)?|"
    r"ближайш\w+(?:\s+к|\s+ко)?|"
    r"недалеко(?:\s+от)?|неподалеку(?:\s+от)?|неподалёку(?:\s+от)?|"
    r"поблизости(?:\s+от)?|"
    r"вблизи|близко(?:\s+к|\s+ко)?|около|возле|"
    r"у|к"
    r")"
)
