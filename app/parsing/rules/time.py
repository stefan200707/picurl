import re
from typing import NamedTuple

from .core import Span, _iter_free, _normalize


class TimeFacts(NamedTuple):
    """Время до метро."""

    time_on_foot: int | None = None
    time_on_transport: int | None = None


_PREP = r"(?:в|до|от|за|не\s+более|менее|на)"
_MINUTES = r"(?:минут\w*|мин\w*)"
_METRO = r"(?:метро|станци\w*)"
_TRANSPORT = r"(?:транспорт\w*|машин\w*|авто|автомобил\w*)"
_FOOT = r"(?:пешком|пешк\w*|шаг\w*|ходьб\w*)"

#: Числительные прописью для минут (находка QA-корпуса №2: «пешком семь минут»/
#: «минут семь» давали ``None`` — только ``(\d+)`` поддерживался). Диапазон
#: 1..30 — разумный для пешей/транспортной доступности до метро (дальше в
#: идиоме практического смысла нет). В отличие от rooms.py (``_CARD_WORD`` —
#: открытый диапазон «3+», 1..5) у минут своя семантика: точное число без
#: схлопывания, поэтому словарь свой и полный, а не переиспользован.
_MINUTE_WORD_TO_NUM: dict[str, int] = {
    "одна": 1,
    "одну": 1,
    "один": 1,
    "две": 2,
    "два": 2,
    "двух": 2,
    "три": 3,
    "трех": 3,
    "четыре": 4,
    "четырех": 4,
    "пять": 5,
    "пяти": 5,
    "шесть": 6,
    "шести": 6,
    "семь": 7,
    "семи": 7,
    "восемь": 8,
    "восьми": 8,
    "девять": 9,
    "девяти": 9,
    "десять": 10,
    "десяти": 10,
    "одиннадцать": 11,
    "двенадцать": 12,
    "тринадцать": 13,
    "четырнадцать": 14,
    "пятнадцать": 15,
    "шестнадцать": 16,
    "семнадцать": 17,
    "восемнадцать": 18,
    "девятнадцать": 19,
    "двадцать": 20,
    "тридцать": 30,
}
#: Отсортировано по убыванию длины, чтобы более длинная альтернатива (напр.
#: «пятнадцать») проверялась раньше короткой («пять») — иначе regex-алгоритм
#: мог бы остановиться на первом совпавшем префиксе альтернативы.
_MINUTE_WORD_PATTERN = "|".join(
    sorted((re.escape(w) for w in _MINUTE_WORD_TO_NUM), key=len, reverse=True)
)
#: Число минут: либо цифры (как раньше), либо числительное прописью из словаря
#: выше. Одна захватывающая группа — group(1), как и было с голым ``(\d+)``.
_MINUTE_NUM = rf"(?:\d+|{_MINUTE_WORD_PATTERN})"


def _parse_minutes(raw: str) -> int:
    """Число минут из захваченной группы (цифры или числительное прописью)."""
    if raw.isdigit():
        return int(raw)
    return _MINUTE_WORD_TO_NUM[raw]


#: Глаголы пешего движения — носитель способа передвижения наравне с «пешком»:
#: «до метро ИДТИ 12 минут». Перечислены явно (без открытого стема «ид\w*»),
#: чтобы не цеплять посторонние формы.
_WALK_VERB = r"(?:идти|ити|дойти|идёт|идет|ходить|добираться)"
#: Идиома «(в пешей/шаговой) доступности» — «в шаговой доступности», «было в
#: доступности». Модель одного предлога между метро и числом (см. _T_FOOT_2) её
#: не покрывала: между «метро» и числом стоят «было в доступности».
_ACCESS = r"(?:пеш\w+\s+|шагов\w+\s+)?доступност\w+"

_T_TRANS_1 = re.compile(
    rf"\b(?:{_PREP}\s+)?({_MINUTE_NUM})(?:\s+{_MINUTES})?(?:\s+{_PREP})?(?:\s+{_METRO})?"
    rf"(?:\s+{_PREP})?\s+{_TRANSPORT}\b"
)
_T_TRANS_2 = re.compile(
    rf"\b(?:{_PREP}\s+)?{_METRO}(?:\s+{_PREP})?\s+({_MINUTE_NUM})(?:\s+{_MINUTES})?"
    rf"(?:\s+{_PREP})?\s+{_TRANSPORT}\b"
)
#: Способ передвижения стоит МЕЖДУ «метро» и числом: «до метро НА ТРАНСПОРТЕ 15
#: минут», «метро НА МАШИНЕ 12 минут». Модель одного предлога между метро и
#: числом (_T_TRANS_2) требует обратный порядок (число раньше транспорта) и такую
#: форму не покрывала.
_T_TRANS_MODE = re.compile(
    rf"\b(?:{_PREP}\s+)?{_METRO}\s+(?:{_PREP}\s+)?{_TRANSPORT}"
    rf"(?:\s+{_PREP})?\s+({_MINUTE_NUM})(?:\s+{_MINUTES})?\b"
)
#: Инверсия «минут N» ВМЕСТО «N минут» — разговорный приближённый оборот
#: («минут семь» ≈ «около семи минут», та же конструкция, что «часов в пять»).
#: Только для MODE (метро явно рядом со способом передвижения) — без метро-
#: якоря голое «минут семь» слишком легко перехватило бы чужое число (см.
#: симметричное решение не вводить голое «от» у landmark-дистанции в CLAUDE.md).
_T_TRANS_MODE_INV = re.compile(
    rf"\b(?:{_PREP}\s+)?{_METRO}\s+(?:{_PREP}\s+)?{_TRANSPORT}"
    rf"(?:\s+{_PREP})?\s+{_MINUTES}\s+({_MINUTE_NUM})\b"
)

_T_FOOT_1 = re.compile(
    rf"\b(?:{_PREP}\s+)?({_MINUTE_NUM})(?:\s+{_MINUTES})?(?:\s+{_PREP})?\s+{_METRO}\b"
)
_T_FOOT_2 = re.compile(
    rf"\b(?:{_PREP}\s+)?{_METRO}(?:\s+{_PREP})?\s+({_MINUTE_NUM})(?:\s+{_MINUTES})?"
    rf"(?:\s+{_FOOT})?\b"
)
_T_FOOT_3 = re.compile(rf"\b(?:{_PREP}\s+)?({_MINUTE_NUM})(?:\s+{_MINUTES})?\s+{_FOOT}\b")
#: «метро … (было в) (пешей/шаговой) доступности N минут» — до 3 незначимых слов
#: между метро и идиомой доступности.
_T_FOOT_ACCESS = re.compile(
    rf"\b{_METRO}(?:\s+\w+){{0,3}}?\s+{_ACCESS}\s+(?:{_PREP}\s+)?({_MINUTE_NUM})\s*{_MINUTES}"
)
#: «в шаговой доступности 7 минут» без явного слова «метро» — доступность к
#: метро подразумевается; дефолт — пеший.
_T_FOOT_ACCESS2 = re.compile(rf"\b{_ACCESS}\s+(?:{_PREP}\s+)?({_MINUTE_NUM})\s*{_MINUTES}")
#: Пеший аналог `_T_TRANS_MODE`: «до метро ПЕШКОМ 7 минут», «метро ПЕШКОМ 7
#: минут», «до метро ИДТИ 12 минут», «до метро ХОДЬБЫ 9 минут». Симметричная
#: форма «до метро 7 минут пешком» покрыта `_T_FOOT_2` (там способ идёт ПОСЛЕ
#: числа); обратный порядок раньше не матчился вовсе, и минуты — реальный
#: URL-фильтр ``timeOnFoot`` — молча превращались в фиктивную дистанцию POI.
_T_FOOT_MODE = re.compile(
    rf"\b(?:{_PREP}\s+)?{_METRO}\s+(?:{_PREP}\s+)?(?:{_FOOT}|{_WALK_VERB})"
    rf"(?:\s+{_PREP})?\s+({_MINUTE_NUM})(?:\s+{_MINUTES})?\b"
)
#: Инверсия «минут N» пешего MODE — «до метро пешком минут семь» (находка
#: QA-корпуса №2). Тот же приближённый оборот, что `_T_TRANS_MODE_INV`; MINUTES
#: здесь ОБЯЗАТЕЛЬНО (без него «до метро пешком семь» неоднозначно — «семь» без
#: явного «минут» рядом мог бы значить что угодно).
_T_FOOT_MODE_INV = re.compile(
    rf"\b(?:{_PREP}\s+)?{_METRO}\s+(?:{_PREP}\s+)?(?:{_FOOT}|{_WALK_VERB})"
    rf"(?:\s+{_PREP})?\s+{_MINUTES}\s+({_MINUTE_NUM})\b"
)

# ---------------------------------------------------------------------------
# Guard «безметровых» форм: минуты до POI ≠ URL-фильтр timeOnFoot
# ---------------------------------------------------------------------------
#
# ``_T_FOOT_3`` и ``_T_FOOT_ACCESS2`` — единственные пешие формы, которые НЕ
# требуют ни «метро», ни «станции». Фраза «до магазинов не больше 12 минут
# ПЕШКОМ» выставляла ими РЕАЛЬНЫЙ URL-фильтр ``timeOnFoot=12`` («пешком до
# метро»), которого пользователь не просил, — и одно число уходило сразу в два
# фильтра. Живой замер вреда: у ЖК «Волжский парк» (id 411) реальный
# ``timeOnFoot=15``, при ``timeOnFoot=12`` ``api.pik.ru`` отдаёт 0 однушек против
# 31 без фильтра — ссылка обещала ЖК, которых pik.ru не показывал.
#
# Это ЗЕРКАЛО обратного guard'а, который в ``rules/poi.py`` есть с самого начала
# («метро»/«станц» в сегменте → это время до метро, а не дистанция POI); у
# правила времени симметричной проверки не было — чистая асимметрия.
#
# Почему лексический guard, а не перестановка правил (гонять POI раньше времени и
# передавать POI-спаны как ``consumed``): зависимость двусторонняя —
# ``poi._LEADING_DISTANCE`` сам опирается на спаны цены/площади/ВРЕМЕНИ, чтобы не
# украсть чужое число. Перестановка потребовала бы двух проходов правила времени;
# лексика решает ровно ту же задачу одной проверкой и в том же стиле, что
# ``stopwords.py`` и ``station_class._is_road_context``.
#
#: Категории POI (в духе ``poi._POI_PATTERNS``). Голые «сад»/«парк»/«лес» в
#: единственном числе взяты ОСТОРОЖНО (падежи перечислены), потому что они
#: омонимичны топонимам-станциям: «Ботанический сад», «Парк Победы», «Лесная».
#: «зелен-» намеренно не включено — «зелёная ветка метро» дала бы ложный POI.
_POI_CUE = re.compile(
    r"магазин|продукт|супермаркет"
    r"|поликлиник|больниц|аптек|роддом|медцентр|клиник|госпитал"
    r"|школ|садик|детсад|детск\w+\s+сад|сад(?:ы|ов|ам|ами|ах)\b"
    r"|парковк|паркинг|парк(?:а|у|е|ом|и|ов|ам|ах)?\b|лес(?:а|у|ом)?\b"
)
#: Слова-носители «это про метро»: их присутствие рядом ОТМЕНЯЕТ guard.
_METRO_CUE = re.compile(r"метро|станц")
#: Границы клаузы. Окно контекста ограничено ОДНИМ пожеланием с обеих сторон:
#: «…пешком, а метро в 5 минутах» — это два независимых пожелания, и «метро» из
#: соседнего не оправдывает ``timeOnFoot`` здесь; симметрично «рядом магазин, в 8
#: минутах пешком» — магазин из соседней клаузы guard не включает.
_CLAUSE_BREAK = re.compile(r"[,;.!?()]")
#: Сколько символов контекста смотреть влево/вправо (внутри клаузы). Проверяются
#: ОБЕ стороны: POI-категория бывает и слева («до магазинов … 12 минут пешком»),
#: и справа («до 20 минут пешком до школы и детского сада»).
_CUE_WINDOW = 70


def _is_poi_time_context(norm: str, span: Span) -> bool:
    """Относятся ли эти минуты к POI, а не к метро (см. блок комментариев выше)."""
    start, end = span
    left = norm[max(0, start - _CUE_WINDOW) : start]
    breaks = list(_CLAUSE_BREAK.finditer(left))
    if breaks:
        left = left[breaks[-1].end() :]

    right = norm[end : end + _CUE_WINDOW]
    first_break = _CLAUSE_BREAK.search(right)
    if first_break is not None:
        right = right[: first_break.start()]

    window = f"{left} {right}"
    if _METRO_CUE.search(window):
        return False
    return _POI_CUE.search(window) is not None


def extract_time_to_metro(text: str) -> tuple[TimeFacts, list[Span]]:
    """Извлечь время до метро."""
    norm = _normalize(text)
    spans: list[Span] = []
    time_on_foot: int | None = None
    time_on_transport: int | None = None

    # Транспорт (MODE_INV — инверсия «минут N» — сразу после прямого MODE,
    # чтобы более специфичная метро-заякоренная форма проверялась раньше общих).
    for pattern in (_T_TRANS_MODE, _T_TRANS_MODE_INV, _T_TRANS_1, _T_TRANS_2):
        for match in _iter_free(pattern, norm, spans):
            if time_on_transport is None:
                time_on_transport = _parse_minutes(match.group(1))
            spans.append(match.span())

    # Пешком (идиомы доступности — раньше явных, длиннее матч → точнее спан)
    for pattern in (
        _T_FOOT_ACCESS,
        _T_FOOT_ACCESS2,
        _T_FOOT_MODE,
        _T_FOOT_MODE_INV,
        _T_FOOT_1,
        _T_FOOT_2,
        _T_FOOT_3,
    ):
        metro_free_form = pattern in (_T_FOOT_ACCESS2, _T_FOOT_3)
        for match in _iter_free(pattern, norm, spans):
            # «Безметровые» формы рядом с POI-категорией — это дистанция до POI, а
            # не время до метро: ни значения, ни спана (спан заберёт POI-правило —
            # см. poi._WALK_TAIL, иначе «пешком» осело бы ложным warning'ом).
            if metro_free_form and _is_poi_time_context(norm, match.span()):
                continue
            if time_on_foot is None:
                time_on_foot = _parse_minutes(match.group(1))
            spans.append(match.span())

    return TimeFacts(time_on_foot, time_on_transport), sorted(spans)
