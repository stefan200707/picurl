#: Префикс перед POI-категорией. Захватываем «нов-» именованной группой ``new``
#: (структурный факт «нужен новый POI» → :attr:`POIRequirement.only_new`).
#: Предлог «с/со» намеренно НЕ захватывается: это чисто грамматическая связка
#: («рядом со школой»), не несущая фильтрующего смысла для pik.ru.
PREFIX = r"(?:(?:с|со)\s+)?(?P<new>\bнов\w+\s+)?"
#: Необязательный СПОСОБ ПЕРЕДВИЖЕНИЯ в хвосте дистанции: «не дальше 15 минут
#: ПЕШКОМ», «до 10 минут ХОДЬБЫ», «5-10 минут ПЕШКОМ». Слово принадлежит той же
#: дистанции до POI и обязано попадать в её спан: иначе, после того как правило
#: времени перестало забирать эти минуты себе (см. guard в ``rules/time.py``),
#: «пешком» оседало бы ложным warning'ом (инвариант 1). Расширяет спан только
#: вправо и только вплотную к уже найденной дистанции — значение фильтра не
#: меняется.
_WALK_WORD = r"(?:пешком|пешк\w+|ходьб\w+|идти|хода)"
_WALK_TAIL = rf"(?:\s+{_WALK_WORD})?"
#: Тот же способ передвижения, но ПЕРЕД величиной: «до школы ИДТИ 12 минут».
#: Без этой ветки регекс дистанции не начинался вовсе — после категории шло не
#: число и не маркер, а слово, — и величина отваливалась в warnings, оставляя
#: требование без ``max_distance_m``. Форма с маркером («идти ДО 12 минут»)
#: работала и раньше, но через другой механизм (``_TRAILING_DISTANCE`` с
#: зазором), которому маркер обязателен как предохранитель, — отсюда и
#: асимметрия, выглядевшая случайной.
#:
#: На маршрут запроса дефект НЕ влиял (проверено): дистанции до POI лежат в
#: кэше, поэтому требование с отсечкой разрешимо детерминированно так же, как и
#: без неё — ``fully_resolved`` остаётся True в обоих случаях. Цена дефекта
#: целиком в выдаче: отсечка не применялась, и в ссылку попадали ЖК, до школы
#: от которых дальше запрошенного.
_WALK_LEAD = rf"(?:{_WALK_WORD}\s+)?"
#: Хвост после POI-категории. Слова «поблизости/рядом/близко» намеренно НЕ
#: сохраняются: близость к POI — это и есть суть POI-требования, отдельного
#: факта тут нет. Дистанцию («в 300 метрах», «не дальше 500 м», «в 1.5 км»)
#: захватываем группами ``dist``/``dist_unit`` (общий фрагмент
#: ``app.parsing.rules.core``, переиспользуемый и в ``station_class.py``) →
#: :attr:`POIRequirement.max_distance_m`.
_DISTANCE = (
    rf"(?:\s+{_WALK_LEAD}(?:{_DIST_MARKER}\s*)?(?P<dist>{_DIST_NUM})\s*(?P<dist_unit>{_DIST_UNIT})"
    rf"{_WALK_TAIL})?"
)
#: Суффиксные формы близости синхронизированы с общим словарём маркеров
#: (``core._PROXIMITY_MARKER``, Milestone AI-20): раньше «недалеко» (без «от»)
#: и голое «рядом» здесь отсутствовали — «школа недалеко» теряла хвост.
#: Предложные формы («у», «к», «около») в суффикс намеренно НЕ входят: после
#: категории POI они вводят СЛЕДУЮЩИЙ объект («школа у метро X»), а не
#: замыкают требование. По той же причине негативные lookahead-ы не дают
#: суффиксу украсть слово, начинающее следующую конструкцию близости:
#: в «детсадом недалеко от метро X» слово «недалеко» принадлежит «недалеко от
#: метро», а не детсаду — иначе маркер метро разрывается и локация теряет
#: контекст.
SUFFIX = (
    r"(?:\s+(?:поблизости(?!\s+от\b)|неподалеку(?!\s+от\b)|неподалёку(?!\s+от\b)"
    r"|недалеко(?!\s+от\b)|рядом(?:\s+с\s+ним\b)?(?!\s+со?\b)"
    r"|близко(?!\s+ко?\b)|вблизи(?!\s+[а-яё])))?"
) + _DISTANCE

#: Разговорное голое «сад» (без слова «детский») тоже означает детсад
#: («новые сады в 300 метрах», «садов поблизости»). Слово «сад» само по себе
#: омонимично топонимам-станциям метро в ед. числе («Ботанический сад»,
#: «Александровский сад» — см. ``app/reference/metro.json``), поэтому голая
#: форма матчится ОСТОРОЖНО в две ступени:
#: 1. Множественное число (``сады``/``садов``/``садам``/``садами``/``садах``) —
#:    однозначно НЕ топоним (те встречаются только в ед. числе) → маркер не
#:    нужен.
#: 2. Единственное число (``сад``) — рискованно, поэтому матчится только при
#:    обязательном (не опциональном) маркере «нов-» перед словом («новый сад»).
#:    Без маркера бытовое «сад» в тексте лучше молча пропустить, чем ложно
#:    сработать на станцию метро.
#: 3. Косвенные падежи ед. числа («до сада», «к саду») — та же омонимия («до
#:    Ботанического сада»), поэтому разрешены только когда предлог расстояния
#:    стоит ВПЛОТНУЮ к слову. Именно прилагательное между предлогом и «садом»
#:    отличает топоним от бытового употребления: «до сада» — детсад, «до
#:    Ботанического сада» — станция. Перечисление окончаний (а не открытый стем
#:    ``сад\w*``) сохраняется намеренно: ``сад\w*`` поглотил бы «садовое»,
#:    «Садовое кольцо», «садоводство».
_SAD_BARE_PLURAL = r"\bсад(?:ы|ов|ам|ами|ах)\b"
_SAD_OBLIQUE_SINGULAR = r"\bсад(?:а|у|ом|е)\b"
_SAD_BARE_SINGULAR_WITH_MARKER = re.compile(
    r"(?:(?:с|со)\s+)?(?P<new>\bнов\w+\s+)\bсад(?:а|у|ом|е)?\b" + SUFFIX
)
_SAD_OBLIQUE_WITH_PREPOSITION = re.compile(
    r"\b(?:до|ко|к|у|возле|около|близ)\s+(?P<new>\bнов\w+\s+)?" + _SAD_OBLIQUE_SINGULAR + SUFFIX
)

